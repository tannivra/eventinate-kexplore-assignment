export const allEvents = [...featuredEvents, ...upcomingEvents]

export function getEventById(id) {
  if (!id) return undefined
  const cleanId = String(id).toLowerCase().trim()
  return allEvents.find((event) => 
    event.id === cleanId || 
    event.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '') === cleanId
  )
}

